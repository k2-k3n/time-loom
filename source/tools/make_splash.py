#!/usr/bin/env python3
"""Build the Time Loom startup asset using the standard library."""
from itertools import groupby
from math import pi, sin
from pathlib import Path
from struct import pack
from zlib import crc32

ROOT = Path(__file__).resolve().parents[1]
WIDTH, HEIGHT = 320, 172
PAPER, INK, BLUE, RUST, SHADOW = 0xF77C, 0x08C6, 0x21EC, 0xCA23, 0xA9A2
FONT = {
    "T": (31, 4, 4, 4, 4, 4, 4),
    "I": (31, 4, 4, 4, 4, 4, 31),
    "M": (17, 27, 21, 21, 17, 17, 17),
    "E": (31, 16, 16, 30, 16, 16, 31),
    "L": (16, 16, 16, 16, 16, 16, 31),
    "O": (14, 17, 17, 17, 17, 17, 14),
    " ": (0,) * 7,
}


def draw(reveal, title):
    pixels = [PAPER] * (WIDTH * HEIGHT)

    def rectangle(x, y, w, h, color):
        for row in range(y, y + h):
            start = row * WIDTH + x
            pixels[start:start + w] = [color] * w

    # The blue warp and rust weft alternate which ribbon crosses on top.
    for x in range(16, reveal):
        wave = sin((x - 16) * 2 * pi / 74)
        blue = (int(89 + 15 * wave), BLUE)
        rust = (int(89 - 15 * wave), RUST)
        ribbons = (blue, rust) if (x - 16) % 74 < 37 else (rust, blue)
        for y, color in ribbons:
            rectangle(x, y + 2, 1, 9, SHADOW)
            rectangle(x, y, 1, 8, color)
    if reveal < 304:
        rectangle(reveal, 62, 2, 69, RUST)
        rectangle(reveal - 2, 60, 6, 3, RUST)
    if title:
        for letter, char in enumerate("TIME LOOM"):
            for row, bits in enumerate(FONT[char]):
                for col in range(5):
                    if bits & (16 >> col):
                        rectangle(107 + letter * 12 + col * 2, 34 + row * 2, 2, 2, INK)
    return pixels


def main():
    frames = [(160, draw(x, False)) for x in range(16, 304, 48)]
    frames.append((610, draw(304, True)))
    payload = bytearray()
    for hold, pixels in frames:
        runs = [(sum(1 for _ in group), color) for color, group in groupby(pixels)]
        payload.extend(pack("<II", hold, len(runs)))
        for count, color in runs:
            payload.extend(pack("<HH", count, color))
    duration = sum(hold for hold, _ in frames)
    data = pack("<4s7I", b"RSP1", 32 + len(payload), crc32(payload), duration,
                WIDTH, HEIGHT, len(frames), 0) + payload
    if len(data) > 24576:
        raise ValueError(f"Startup asset is {len(data)} bytes, exceeding 24576 bytes")
    rows = ["    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ","
            for i in range(0, len(data), 16)]
    (ROOT / "src/splash_data.h").write_text(
        "// Generated by tools/make_splash.py.\n#pragma once\n#include <stdint.h>\n"
        "static const uint8_t kSplash[] = {\n" + "\n".join(rows) + "\n};\n")
    (ROOT / "build").mkdir(exist_ok=True)
    (ROOT / "build/time-loom.rsp").write_bytes(data)
    print(f"{len(data)} bytes, {len(frames)} frames, {duration} ms, CRC32 {crc32(data)}")


if __name__ == "__main__":
    main()
